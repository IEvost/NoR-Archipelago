"""Night of Revenge (D-lis) - Archipelago world.

Static template; item/location data lives in data.py, generated by tools/NoR.ApWorldGen from the project's
data tables (do not edit data.py by hand).

v1 = "vanilla progression": door keys, karma sources and story events stay in their vanilla places, so no
shuffled item gates progress and every location is in logic from the start (reaching it only takes playing).
"""
from typing import Any, Dict

from BaseClasses import Item, ItemClassification, Location, Region, Tutorial
from worlds.AutoWorld import WebWorld, World

from . import data
from .options import NightOfRevengeOptions


class NightOfRevengeItem(Item):
    game = "Night of Revenge"


class NightOfRevengeLocation(Location):
    game = "Night of Revenge"


class NightOfRevengeWeb(WebWorld):
    theme = "dirt"
    tutorials = [Tutorial(
        "Multiworld Setup Guide",
        "How to install the Night of Revenge Archipelago mod and connect to a multiworld.",
        "English",
        "setup_en.md",
        "setup/en",
        ["NoR Archipelago contributors"],
    )]


CLASSIFICATION = {
    "progression": ItemClassification.progression,
    "useful": ItemClassification.useful,
    "filler": ItemClassification.filler,
    "trap": ItemClassification.trap,
}


class NightOfRevengeWorld(World):
    """A dark-fantasy action game: Aradia, a witch, seeks revenge across a ruined, corrupted city."""

    game = "Night of Revenge"
    web = NightOfRevengeWeb()
    options_dataclass = NightOfRevengeOptions
    options: NightOfRevengeOptions
    topology_present = False

    item_name_to_id = {name: info["id"] for name, info in data.ITEMS.items()}
    location_name_to_id = {name: info["id"] for name, info in data.LOCATIONS.items()}

    def _included(self, info: Dict[str, Any]) -> bool:
        category = info["category"]
        if category == "shop":
            return info["slot"] < self.options.shop_slots.value
        if category == "boss_drop":
            return bool(self.options.boss_drops.value)
        if category == "npc":
            return bool(self.options.npc_rewards.value)
        if category == "trade":
            return bool(self.options.trades.value)
        return True

    def create_regions(self) -> None:
        menu = Region("Menu", self.player, self.multiworld)
        world = Region("Night of Revenge", self.player, self.multiworld)
        self.multiworld.regions += [menu, world]
        menu.connect(world)

        for name, info in data.LOCATIONS.items():
            if self._included(info):
                world.locations.append(NightOfRevengeLocation(self.player, name, info["id"], world))

        goal = NightOfRevengeLocation(self.player, "Defeat the Witch in the Thorns", None, world)
        goal.place_locked_item(NightOfRevengeItem("Victory", ItemClassification.progression, None, self.player))
        world.locations.append(goal)

    def create_items(self) -> None:
        pool = []
        for name, info in data.LOCATIONS.items():
            if self._included(info):
                pool.extend(info["vanilla"])

        # Replace a share of the filler items with traps.
        filler_indices = [i for i, n in enumerate(pool) if data.ITEMS[n]["classification"] == "filler"]
        trap_count = len(filler_indices) * self.options.trap_percentage.value // 100
        for i in self.random.sample(filler_indices, trap_count):
            pool[i] = self.random.choice(data.TRAPS)

        self.multiworld.itempool += [self.create_item(n) for n in pool]

    def create_item(self, name: str) -> NightOfRevengeItem:
        info = data.ITEMS[name]
        return NightOfRevengeItem(name, CLASSIFICATION[info["classification"]], info["id"], self.player)

    def get_filler_item_name(self) -> str:
        return data.FILLER_ITEM

    def set_rules(self) -> None:
        self.multiworld.completion_condition[self.player] = lambda state: state.has("Victory", self.player)

    def fill_slot_data(self) -> Dict[str, Any]:
        return {
            "version": data.DATA_VERSION,
            "shop_slots": self.options.shop_slots.value,
            "boss_drops": self.options.boss_drops.value,
            "npc_rewards": self.options.npc_rewards.value,
            "trades": self.options.trades.value,
            "enemy_randomizer": self.options.enemy_randomizer.value,
            "trap_percentage": self.options.trap_percentage.value,
            "death_link": self.options.death_link.value,
            "death_link_mode": self.options.death_link_mode.value,
            "seed": self.random.randint(1, 999_999_999),
        }
