using System.Text.Json;
using System.Text.Json.Nodes;

namespace NoR.DataBuilder;

internal sealed record GameItem(
    string Schema,   // weapon | UseItem | crestring | magic
    int Index,       // position in GDEDataManager.GetAllItems<T>() == ID used by Pickup_item
    string Key,      // GDE entry key
    int? GdeId,      // "ID" field when present
    string? Name,    // internal name (sprite / code name)
    string? NameJp,  // display name
    int? Buy);

internal sealed class Items
{
    public readonly List<GameItem> All = new();
    private readonly Dictionary<(string, int), GameItem> _byIndex = new();
    private readonly Dictionary<string, GameItem> _magicByName = new(StringComparer.Ordinal);

    public static readonly string[] Schemas = { "weapon", "UseItem", "crestring", "magic" };

    public GameItem? Get(string schema, int index) => _byIndex.GetValueOrDefault((schema, index));
    public GameItem? Magic(string name) => _magicByName.GetValueOrDefault(name);

    public static Items Build(string gdePath)
    {
        // GetAllItems<T>() enumerates the master dictionary in insertion order (= file order)
        // and keeps entries whose _gdeSchema matches, so the per-schema file order is the runtime index.
        using var doc = JsonDocument.Parse(File.ReadAllText(gdePath));
        var result = new Items();
        var counters = Schemas.ToDictionary(s => s, _ => 0);

        foreach (var prop in doc.RootElement.EnumerateObject())
        {
            if (prop.Name.StartsWith("_gde", StringComparison.Ordinal)) continue; // schema definitions
            var e = prop.Value;
            if (e.ValueKind != JsonValueKind.Object || !e.TryGetProperty("_gdeSchema", out var schemaEl)) continue;
            string schema = schemaEl.GetString() ?? "";
            if (!counters.ContainsKey(schema)) continue;

            var item = new GameItem(
                schema,
                counters[schema]++,
                prop.Name,
                Int(e, "ID"),
                Str(e, "name"),
                Str(e, "Itemname") ?? Str(e, "magicname") ?? Str(e, "Magicname") ?? Str(e, "jpname"),
                Int(e, "buy"));
            result.All.Add(item);
            result._byIndex[(schema, item.Index)] = item;
            if (schema == "magic" && item.Name != null) result._magicByName[item.Name] = item;
        }
        return result;
    }

    private static string? Str(JsonElement e, string name) =>
        e.TryGetProperty(name, out var v) && v.ValueKind == JsonValueKind.String ? v.GetString() : null;

    private static int? Int(JsonElement e, string name) =>
        e.TryGetProperty(name, out var v) && v.ValueKind == JsonValueKind.Number && v.TryGetInt32(out var i) ? i : null;

    public JsonNode ToJson()
    {
        var root = new JsonObject
        {
            ["_comment"] = "Generated by NoR.DataBuilder from GDE gde_data. 'index' is the runtime list index used by pickups and ItemInventory.",
        };
        foreach (var schema in Schemas)
        {
            var arr = new JsonArray();
            foreach (var i in All.Where(x => x.Schema == schema))
            {
                arr.Add(new JsonObject
                {
                    ["index"] = i.Index,
                    ["key"] = i.Key,
                    ["gdeId"] = i.GdeId,
                    ["name"] = i.Name,
                    ["nameJp"] = i.NameJp,
                    ["buy"] = i.Buy,
                });
            }
            root[schema] = arr;
        }
        return root;
    }
}
