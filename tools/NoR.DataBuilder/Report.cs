using System.Text;

namespace NoR.DataBuilder;

internal static class Report
{
    public static string Build(Items items, Locations locs, SceneData scenes)
    {
        var sb = new StringBuilder();
        sb.AppendLine("# Static data report (generated)");
        sb.AppendLine();
        sb.AppendLine("Generated by `NoR.DataBuilder` from the offline scene scan. Do not edit by hand.");
        sb.AppendLine();

        sb.AppendLine("## Items (GameDataEditor)");
        sb.AppendLine();
        sb.AppendLine("| Schema | Count |");
        sb.AppendLine("|---|---|");
        foreach (var s in Items.Schemas) sb.AppendLine($"| {s} | {items.All.Count(i => i.Schema == s)} |");
        sb.AppendLine();

        sb.AppendLine("## Location candidates per category");
        sb.AppendLine();
        sb.AppendLine("| Category | Count | Inactive at scene start |");
        sb.AppendLine("|---|---|---|");
        foreach (var g in locs.All.GroupBy(l => l.Category).OrderBy(g => g.Key))
            sb.AppendLine($"| {g.Key} | {g.Count()} | {g.Count(l => !l.ActiveAtStart)} |");
        sb.AppendLine();

        sb.AppendLine("## Location candidates per scene");
        sb.AppendLine();
        sb.AppendLine("| # | Scene | Floor | Chest | Magic | Slave |");
        sb.AppendLine("|---|---|---|---|---|---|");
        foreach (var g in locs.All.GroupBy(l => (l.SceneIndex, l.Scene)).OrderBy(g => g.Key.SceneIndex))
        {
            sb.AppendLine($"| {g.Key.SceneIndex} | {g.Key.Scene} | {g.Count(l => l.Category == "floor_item")} | {g.Count(l => l.Category == "chest")} | {g.Count(l => l.Category == "magic")} | {g.Count(l => l.Category == "slave_rescue")} |");
        }
        sb.AppendLine();

        sb.AppendLine("## Enemy spawn points per scene (enemy randomizer input)");
        sb.AppendLine();
        sb.AppendLine("| # | Scene | Spawns | Distinct enemy prefabs |");
        sb.AppendLine("|---|---|---|---|");
        foreach (var g in scenes.OfType("Spawnenemy").GroupBy(c => (c.SceneIndex, c.Scene)).OrderBy(g => g.Key.SceneIndex))
        {
            var prefabs = g.Select(c => c.PtrName("enemy") ?? "null").Distinct().OrderBy(x => x, StringComparer.Ordinal);
            sb.AppendLine($"| {g.Key.SceneIndex} | {g.Key.Scene} | {g.Count()} | {string.Join(", ", prefabs)} |");
        }
        sb.AppendLine();

        var allPrefabs = scenes.OfType("Spawnenemy").GroupBy(c => c.PtrName("enemy") ?? "null").OrderByDescending(g => g.Count());
        sb.AppendLine("## Enemy prefab usage");
        sb.AppendLine();
        sb.AppendLine("| Prefab | Spawn points | Scenes |");
        sb.AppendLine("|---|---|---|");
        foreach (var g in allPrefabs)
            sb.AppendLine($"| {g.Key} | {g.Count()} | {g.Select(c => c.Scene).Distinct().Count()} |");
        sb.AppendLine();

        sb.AppendLine("## Anomalies to verify in the playthrough");
        sb.AppendLine();
        if (locs.Anomalies.Count == 0) sb.AppendLine("None.");
        foreach (var a in locs.Anomalies) sb.AppendLine("- " + a);
        return sb.ToString();
    }
}
