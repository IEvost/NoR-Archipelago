using System.Text.Encodings.Web;
using System.Text.Json;
using System.Text.Json.Nodes;

namespace NoR.DataBuilder;

/// <summary>
/// Builds the project's data tables from the raw static dump produced by NoR.SceneScanner.
///
///   data/items.json             every GDE item (weapon / UseItem / crestring / magic) with its runtime list index
///   data/locations.draft.json   candidate AP locations found in scenes (floor items, chests, magic pickups, slave rescues)
///   data/report.md              human-readable summary + anomalies to check in the playthrough
///
/// Usage: NoR.DataBuilder --dump dump\static --out data
/// </summary>
internal static class Program
{
    private static readonly JsonSerializerOptions JsonOut = new()
    {
        WriteIndented = true,
        Encoder = JavaScriptEncoder.UnsafeRelaxedJsonEscaping,
    };

    private static int Main(string[] args)
    {
        string dump = "dump/static", outDir = "data";
        for (int i = 0; i + 1 < args.Length; i += 2)
        {
            if (args[i] == "--dump") dump = args[i + 1];
            else if (args[i] == "--out") outDir = args[i + 1];
        }
        Directory.CreateDirectory(outDir);

        var items = Items.Build(Path.Combine(dump, "textassets", "gde_data.txt"));
        Write(Path.Combine(outDir, "items.json"), items.ToJson());

        var scenes = SceneData.Load(Path.Combine(dump, "scenes"));
        var locs = Locations.Build(scenes, items);
        Write(Path.Combine(outDir, "locations.draft.json"), locs.ToJson());
        Directory.CreateDirectory(Path.Combine(outDir, "runtime"));
        File.WriteAllText(Path.Combine(outDir, "runtime", "locations.tsv"), locs.ToRuntimeTsv(), new System.Text.UTF8Encoding(false));
        Console.WriteLine("wrote " + Path.Combine(outDir, "runtime", "locations.tsv"));

        // Enemy catalog for the enemy randomizer: scene -> distinct prefabs referenced by its Spawnenemy points.
        var enemySb = new System.Text.StringBuilder("# generated by NoR.DataBuilder - do not edit\n#scene\tspawnCount\tprefabs\n");
        foreach (var g in scenes.OfType("Spawnenemy").GroupBy(c => c.Scene).OrderBy(g => g.First().SceneIndex))
        {
            var prefabs = g.Select(c => c.PtrName("enemy")).Where(n => n != null).Distinct().OrderBy(n => n, StringComparer.Ordinal);
            enemySb.Append(g.Key).Append('\t').Append(g.Count()).Append('\t').Append(string.Join(",", prefabs)).Append('\n');
        }
        File.WriteAllText(Path.Combine(outDir, "runtime", "enemies.tsv"), enemySb.ToString(), new System.Text.UTF8Encoding(false));
        Console.WriteLine("wrote " + Path.Combine(outDir, "runtime", "enemies.tsv"));

        var regions = Regions.Build(scenes);
        Write(Path.Combine(outDir, "regions.draft.json"), regions.ToJson());
        File.WriteAllText(Path.Combine(outDir, "report.md"), Report.Build(items, locs, scenes) + "\n" + regions.ToMarkdown(locs));
        Console.WriteLine($"items: {items.All.Count}, locations: {locs.All.Count}, anomalies: {locs.Anomalies.Count}");
        return 0;
    }

    private static void Write(string path, JsonNode node)
    {
        File.WriteAllText(path, node.ToJsonString(JsonOut) + "\n");
        Console.WriteLine("wrote " + path);
    }
}
