using System.Security.Cryptography;
using System.Text;
using System.Text.Encodings.Web;
using System.Text.Json;
using Mono.Cecil;
using Mono.Cecil.Cil;

namespace NoR.TextExtractor;

/// <summary>
/// Collects every Japanese string the game can display, from three sources:
///   code   string literals (ldstr) in Assembly-CSharp.dll, identified by method + occurrence
///   gde    String fields of GameDataEditor entries (item names, descriptions, ...)
///   scene  serialized strings in scenes/prefabs (from NoR.SceneScanner's text/jp_strings.jsonl)
///
/// Output (local only, contains game text - never commit):
///   dump/text/source.jsonl   one entry per occurrence: id, source, context, jp, hash
///   dump/text/unique.tsv     unique Japanese strings with occurrence count (translation work list)
///   dump/text/stats.txt
///
/// The committed translation files only store id + hash + English, so the repository never
/// contains the original Japanese text. The hash detects changed source strings.
///
/// Usage: NoR.TextExtractor --game "<game dir>" --scan dump\static --out dump\text
/// </summary>
internal static class Program
{
    private static readonly JsonSerializerOptions Json = new() { Encoder = JavaScriptEncoder.UnsafeRelaxedJsonEscaping };

    private sealed record Entry(string Id, string Source, string Context, string Jp)
    {
        public string Hash => HashOf(Jp);
    }

    private static int Main(string[] args)
    {
        string game = "", scan = "dump/static", outDir = "dump/text", refCache = "";
        int batchSize = 120;
        for (int i = 0; i + 1 < args.Length; i += 2)
        {
            switch (args[i])
            {
                case "--game": game = args[i + 1]; break;
                case "--scan": scan = args[i + 1]; break;
                case "--out": outDir = args[i + 1]; break;
                case "--ref": refCache = args[i + 1]; break;          // optional XUnity cache used as reference hints
                case "--batch-size": batchSize = int.Parse(args[i + 1]); break;
            }
        }
        if (game.Length == 0) { Console.Error.WriteLine("Usage: NoR.TextExtractor --game <dir> [--scan dump\\static] [--out dump\\text]"); return 2; }
        Directory.CreateDirectory(outDir);

        var entries = new List<Entry>();
        entries.AddRange(FromCode(Path.Combine(game, "NightofRevenge_Data", "Managed", "Assembly-CSharp.dll")));
        entries.AddRange(FromGde(Path.Combine(scan, "textassets", "gde_data.txt")));
        entries.AddRange(FromScenes(Path.Combine(scan, "text", "jp_strings.jsonl")));

        using (var w = new StreamWriter(Path.Combine(outDir, "source.jsonl"), false, new UTF8Encoding(false)))
        {
            foreach (var e in entries)
                w.WriteLine(JsonSerializer.Serialize(new { id = e.Id, src = e.Source, ctx = e.Context, hash = e.Hash, jp = e.Jp }, Json));
        }

        var unique = entries.GroupBy(e => e.Jp).OrderByDescending(g => g.Count()).ToList();
        using (var w = new StreamWriter(Path.Combine(outDir, "unique.tsv"), false, new UTF8Encoding(false)))
        {
            w.WriteLine("#hash\tcount\tsources\tjp (\\n escaped)");
            foreach (var g in unique)
                w.WriteLine($"{HashOf(g.Key)}\t{g.Count()}\t{string.Join(",", g.Select(e => e.Source).Distinct())}\t{Escape(g.Key)}");
        }

        // Unsafe code literals: committed as hashes only (no game text), read by the runtime transpiler.
        File.WriteAllText(Path.Combine(outDir, "code_unsafe_reasons.tsv"), "#hash\tmethod\tconsumer\n" + string.Join("\n", UnsafeReasons) + "\n", new UTF8Encoding(false));
        string committed = Path.Combine("data", "translation", "code_unsafe.txt");
        Directory.CreateDirectory(Path.GetDirectoryName(committed)!);
        File.WriteAllText(committed,
            "# Hashes of Japanese code literals used as logic keys - never translate. Generated by NoR.TextExtractor.\n" +
            string.Join("\n", UnsafeLiterals.Select(HashOf).OrderBy(h => h, StringComparer.Ordinal)) + "\n");
        // Methods containing Japanese literals: the runtime only transpiles these (identifiers only, no text).
        var methods = entries.Where(e => e.Source == "code").Select(e => e.Id.Substring(5, e.Id.LastIndexOf('#') - 5)).Distinct().OrderBy(x => x, StringComparer.Ordinal);
        File.WriteAllText(Path.Combine("data", "translation", "code_methods.txt"),
            "# Methods of Assembly-CSharp containing Japanese string literals (Type::Name(ParamTypeNames)). Generated by NoR.TextExtractor.\n" +
            string.Join("\n", methods) + "\n");

        Console.WriteLine($"unsafe code literals: {UnsafeLiterals.Count} (of {entries.Where(e => e.Source == "code").Select(e => e.Jp).Distinct().Count()} unique)");

        WriteBatches(entries, Path.Combine(outDir, "batches"), batchSize, LoadReference(refCache));

        var stats = new StringBuilder();
        foreach (var g in entries.GroupBy(e => e.Source))
        {
            var u = g.Select(e => e.Jp).Distinct().ToList();
            stats.AppendLine($"{g.Key,-6} occurrences {g.Count(),6}  unique {u.Count,6}  chars {u.Sum(s => s.Length),8}");
        }
        stats.AppendLine($"total  occurrences {entries.Count,6}  unique {unique.Count,6}  chars {unique.Sum(g => g.Key.Length),8}");
        File.WriteAllText(Path.Combine(outDir, "stats.txt"), stats.ToString());
        Console.Write(stats);
        return 0;
    }

    // ------------------------------------------------------------------ code literals

    /// <summary>Japanese code literals that act as logic keys (compared, used as asset/animation names, saved keys).</summary>
    internal static readonly HashSet<string> UnsafeLiterals = new(StringComparer.Ordinal);
    internal static readonly List<string> UnsafeReasons = new();

    // Calls whose string argument is an identifier, not display text.
    private static readonly HashSet<string> KeyConsumers = new(StringComparer.Ordinal)
    {
        "op_Equality", "op_Inequality", "Equals", "Contains", "StartsWith", "EndsWith", "IndexOf", "Compare", "CompareTo",
        "SetAnimation", "AddAnimation", "SetSkin", "SetAttachment", "FindAnimation", "FindBone", "FindSlot", "GetAttachment",
        "Find", "FindWithTag", "FindGameObjectWithTag", "FindGameObjectsWithTag", "FindChild", "CompareTag",
        "Load", "LoadAll", "LoadScene", "LoadSceneAsync", "UnloadSceneAsync", "GetSceneByName",
        "PlaySound", "PlaySound3DAtTransform", "StopAllOfSound", "FadeSoundGroupToVolume", "ChangePlaylistByName", "PlaySoundAndForget",
        "SetTrigger", "SetBool", "SetInteger", "SetFloat", "Play", "CrossFade", "Invoke", "InvokeRepeating", "CancelInvoke",
        "StartCoroutine", "StopCoroutine", "SendMessage", "BroadcastMessage", "GetSprite", "GetComponent", "AddComponent",
        "Add", "ContainsKey", "TryGetValue", "get_Item", "set_Item", "Remove",
        "Save", "Exists", "Delete", "GetInt", "SetInt", "GetString", "SetString", "HasKey",
    };

    private static IEnumerable<Entry> FromCode(string dll)
    {
        var resolver = new DefaultAssemblyResolver();
        resolver.AddSearchDirectory(Path.GetDirectoryName(dll)!);
        using var asm = AssemblyDefinition.ReadAssembly(dll, new ReaderParameters { AssemblyResolver = resolver });
        var result = new List<Entry>();
        foreach (var type in AllTypes(asm.MainModule.Types))
        {
            foreach (var m in type.Methods)
            {
                if (!m.HasBody) continue;
                int n = 0;
                var ins = m.Body.Instructions;
                for (int k = 0; k < ins.Count; k++)
                {
                    if (ins[k].OpCode != OpCodes.Ldstr) continue;
                    var s = (string)ins[k].Operand;
                    int index = n++;
                    if (!ContainsJapanese(s)) continue;

                    // Look at the instruction(s) consuming the literal. Literals that go into a key-like call are unsafe.
                    for (int j = k + 1; j < Math.Min(ins.Count, k + 4); j++)
                    {
                        var op = ins[j].OpCode;
                        if ((op == OpCodes.Call || op == OpCodes.Callvirt || op == OpCodes.Newobj) && ins[j].Operand is MethodReference mr)
                        {
                            if (KeyConsumers.Contains(mr.Name) && !(mr.Name == "Add" && mr.DeclaringType.Name.StartsWith("List", StringComparison.Ordinal)))
                            {
                                if (UnsafeLiterals.Add(s)) UnsafeReasons.Add($"{HashOf(s)}\t{type.FullName}.{m.Name}\t{mr.DeclaringType.Name}.{mr.Name}");
                            }
                            break;
                        }
                        if (op == OpCodes.Beq || op == OpCodes.Bne_Un || op == OpCodes.Ceq) break;
                        if (op == OpCodes.Ldstr) break;
                    }
                    // id: method identity + index among ldstr instructions of that method (stable across rebuilds of our tools)
                    result.Add(new Entry($"code:{type.FullName}::{MethodKey(m)}#{index}", "code", $"{type.FullName}.{m.Name}", s));
                }
            }
        }
        return result;
    }

    private static IEnumerable<TypeDefinition> AllTypes(IEnumerable<TypeDefinition> types)
    {
        foreach (var t in types)
        {
            yield return t;
            foreach (var n in AllTypes(t.NestedTypes)) yield return n;
        }
    }

    internal static string MethodKey(MethodDefinition m) =>
        m.Name + "(" + string.Join(",", m.Parameters.Select(p => p.ParameterType.Name)) + ")";

    // ------------------------------------------------------------------ GDE data

    private static IEnumerable<Entry> FromGde(string path)
    {
        if (!File.Exists(path)) { Console.Error.WriteLine("GDE data not found: " + path); yield break; }
        using var doc = JsonDocument.Parse(File.ReadAllText(path));
        foreach (var entry in doc.RootElement.EnumerateObject())
        {
            if (entry.Name.StartsWith("_gde", StringComparison.Ordinal) || entry.Value.ValueKind != JsonValueKind.Object) continue;
            string schema = entry.Value.TryGetProperty("_gdeSchema", out var s) ? s.GetString() ?? "" : "";
            foreach (var f in entry.Value.EnumerateObject())
            {
                if (f.Name.StartsWith("_gde", StringComparison.Ordinal)) continue;
                if (f.Value.ValueKind == JsonValueKind.String)
                {
                    var v = f.Value.GetString();
                    if (ContainsJapanese(v)) yield return new Entry($"gde:{entry.Name}.{f.Name}", "gde", schema, v!);
                }
                else if (f.Value.ValueKind == JsonValueKind.Array)
                {
                    int i = 0;
                    foreach (var item in f.Value.EnumerateArray())
                    {
                        if (item.ValueKind == JsonValueKind.String && ContainsJapanese(item.GetString()))
                            yield return new Entry($"gde:{entry.Name}.{f.Name}[{i}]", "gde", schema, item.GetString()!);
                        i++;
                    }
                }
            }
        }
    }

    // ------------------------------------------------------------------ scenes / prefabs

    private static IEnumerable<Entry> FromScenes(string path)
    {
        if (!File.Exists(path)) { Console.Error.WriteLine("Scene strings not found: " + path); yield break; }
        var seen = new Dictionary<string, int>();
        foreach (var line in File.ReadLines(path))
        {
            using var doc = JsonDocument.Parse(line);
            var r = doc.RootElement;
            string file = r.GetProperty("file").GetString()!;
            string obj = r.GetProperty("obj").GetString()!;
            string comp = r.GetProperty("component").GetString()!;
            string field = r.GetProperty("field").GetString()!;
            string text = r.GetProperty("text").GetString()!;
            string id = $"scene:{file}:{obj}:{comp}:{field}";
            // Sibling objects can share the same path; disambiguate by occurrence order.
            seen[id] = seen.TryGetValue(id, out var n) ? n + 1 : 0;
            if (seen[id] > 0) id += "#" + seen[id];
            yield return new Entry(id, "scene", r.GetProperty("scene").GetString()!, text);
        }
    }

    // ------------------------------------------------------------------ translation batches

    /// <summary>
    /// Work packages for translators: one JSONL file per ~batchSize unique strings, grouped by source and context
    /// so related lines (one NPC's dialogue, one item list) stay together. Strings already translated in
    /// data/translation/en/*.tsv and unsafe literals are skipped.
    /// Line: {"hash","src","ctx","jp","ref"?} ; expected answer per line: hash \t english
    /// </summary>
    private static void WriteBatches(List<Entry> entries, string dir, int size, Dictionary<string, string> reference)
    {
        if (Directory.Exists(dir)) Directory.Delete(dir, true);
        Directory.CreateDirectory(dir);

        var done = new HashSet<string>(StringComparer.Ordinal);
        string enDir = Path.Combine("data", "translation", "en");
        if (Directory.Exists(enDir))
            foreach (var f in Directory.GetFiles(enDir, "*.tsv"))
                foreach (var line in File.ReadLines(f))
                {
                    if (line.Length == 0 || line[0] == '#') continue;
                    var p = line.Split('\t');
                    if (p.Length >= 2 && p[1].Length > 0) done.Add(p[0]);
                }

        int refHits = 0;
        foreach (var src in new[] { "gde", "code", "scene" })
        {
            var unique = entries.Where(e => e.Source == src && !UnsafeLiterals.Contains(e.Jp))
                .GroupBy(e => e.Jp).Select(g => g.First())
                .Where(e => !done.Contains(e.Hash))
                .OrderBy(e => e.Context, StringComparer.Ordinal).ThenBy(e => e.Id, StringComparer.Ordinal)
                .ToList();
            for (int b = 0; b * size < unique.Count; b++)
            {
                using var w = new StreamWriter(Path.Combine(dir, $"{src}_{b:000}.jsonl"), false, new UTF8Encoding(false));
                foreach (var e in unique.Skip(b * size).Take(size))
                {
                    reference.TryGetValue(e.Jp, out var hint);
                    if (hint != null) refHits++;
                    w.WriteLine(JsonSerializer.Serialize(new { hash = e.Hash, src = e.Source, ctx = e.Context, jp = e.Jp, @ref = hint }, Json));
                }
            }
            Console.WriteLine($"batches {src}: {unique.Count} strings in {(unique.Count + size - 1) / size} files");
        }
        Console.WriteLine($"reference hints matched: {refHits}");
    }

    /// <summary>Reads an XUnity AutoTranslator cache ("jp=en", \n escaped). Exact matches only.</summary>
    private static Dictionary<string, string> LoadReference(string path)
    {
        var d = new Dictionary<string, string>(StringComparer.Ordinal);
        if (path.Length == 0 || !File.Exists(path)) return d;
        foreach (var line in File.ReadLines(path))
        {
            if (line.Length == 0 || line.StartsWith("//") || line.StartsWith("r:")) continue;
            int eq = FindUnescapedEquals(line);
            if (eq <= 0) continue;
            string jp = XUnescape(line[..eq]), en = XUnescape(line[(eq + 1)..]);
            if (ContainsJapanese(jp) && en.Length > 0 && !ContainsJapanese(en)) d[jp] = en;
        }
        return d;
    }

    private static int FindUnescapedEquals(string s)
    {
        for (int i = 0; i < s.Length; i++)
        {
            if (s[i] == '\\') { i++; continue; }
            if (s[i] == '=') return i;
        }
        return -1;
    }

    private static string XUnescape(string s) => s.Replace("\\n", "\n").Replace("\\=", "=").Replace("\\\\", "\\");

    // ------------------------------------------------------------------ helpers

    internal static bool ContainsJapanese(string? s)
    {
        if (string.IsNullOrEmpty(s)) return false;
        foreach (char c in s)
            if ((c >= '\u3040' && c <= '\u30ff') || (c >= '\u4e00' && c <= '\u9fff') || (c >= '\uff00' && c <= '\uffef'))
                return true;
        return false;
    }

    internal static string HashOf(string s) =>
        Convert.ToHexString(SHA1.HashData(Encoding.UTF8.GetBytes(s)))[..12].ToLowerInvariant();

    private static string Escape(string s) => s.Replace("\\", "\\\\").Replace("\t", "\\t").Replace("\r", "").Replace("\n", "\\n");
}
